"""Inject the Yool theme assets into the Vue SPAs (Helpdesk, CRM) without editing those apps.

Helpdesk's /helpdesk page is a standalone HTML document (helpdesk/www/helpdesk/index.html, generated by
Helpdesk's Vite build) that never renders app_include_* / web_include_* assets. Frappe runs every
`after_request` hook with the finished response (frappe/app.py: run_after_request_hooks), so we add our
<link>/<script> tags right before </head> of that HTML response. API calls, assets and every other page
pass through untouched (path + content-type checks), and the edit is skipped if the tags are already there
(e.g. when the manual snippet from server_patch/ was applied too).
"""

import frappe

import yool_theme

# path prefix -> (stylesheets, scripts)
TARGETS = {
	"/helpdesk": (
		["/assets/yool_theme/css/helpdesk_theme.css"],
		["/assets/yool_theme/js/helpdesk_theme.js"],
	),
	"/crm": (["/assets/yool_theme/css/crm_theme.css"], []),
}

MARKER = "yool_theme:spa-assets"


def _target(path):
	for prefix, assets in TARGETS.items():
		if path == prefix or path.startswith(prefix + "/"):
			return assets
	return None


def _version():
	try:
		return f"{yool_theme.__version__}-{frappe.utils.get_build_version()}"
	except Exception:
		return yool_theme.__version__


def inject_spa_assets(response=None, request=None):
	"""after_request hook. Must never raise: any problem leaves the response unchanged."""
	try:
		if response is None or request is None or request.method != "GET":
			return
		if response.status_code != 200 or response.direct_passthrough or response.mimetype != "text/html":
			return
		assets = _target(request.path or "")
		if not assets:
			return

		html = response.get_data(as_text=True)
		head_end = html.find("</head>")
		if head_end == -1 or MARKER in html or "/assets/yool_theme/" in html:
			return

		v = _version()
		css, js = assets
		tags = [f"<!-- {MARKER} -->"]
		tags += [f'<link rel="stylesheet" href="{href}?v={v}">' for href in css]
		tags += [f'<script defer src="{src}?v={v}"></script>' for src in js]
		response.set_data(html[:head_end] + "\n".join(tags) + "\n" + html[head_end:])
	except Exception:
		frappe.logger("yool_theme").exception("yool_theme: could not inject SPA assets")
